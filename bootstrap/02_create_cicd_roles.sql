USE ROLE SECURITYADMIN;

CREATE ROLE IF NOT EXISTS RETAIL_DEV_DEPLOYER;
CREATE ROLE IF NOT EXISTS RETAIL_UAT_DEPLOYER;
CREATE ROLE IF NOT EXISTS RETAIL_PROD_DEPLOYER;

GRANT USAGE ON WAREHOUSE RETAIL_DEV_WH TO ROLE RETAIL_DEV_DEPLOYER;
GRANT USAGE ON WAREHOUSE RETAIL_UAT_WH TO ROLE RETAIL_UAT_DEPLOYER;
GRANT USAGE ON WAREHOUSE RETAIL_PROD_WH TO ROLE RETAIL_PROD_DEPLOYER;

GRANT USAGE ON DATABASE RETAIL_DEV TO ROLE RETAIL_DEV_DEPLOYER;
GRANT USAGE ON DATABASE RETAIL_UAT TO ROLE RETAIL_UAT_DEPLOYER;
GRANT USAGE ON DATABASE RETAIL_PROD TO ROLE RETAIL_PROD_DEPLOYER;

GRANT USAGE ON ALL SCHEMAS IN DATABASE RETAIL_DEV TO ROLE RETAIL_DEV_DEPLOYER;
GRANT USAGE ON ALL SCHEMAS IN DATABASE RETAIL_UAT TO ROLE RETAIL_UAT_DEPLOYER;
GRANT USAGE ON ALL SCHEMAS IN DATABASE RETAIL_PROD TO ROLE RETAIL_PROD_DEPLOYER;

GRANT CREATE TABLE, CREATE VIEW, CREATE FILE FORMAT, CREATE STAGE, CREATE PROCEDURE
ON ALL SCHEMAS IN DATABASE RETAIL_DEV TO ROLE RETAIL_DEV_DEPLOYER;
GRANT CREATE TABLE, CREATE VIEW, CREATE FILE FORMAT, CREATE STAGE, CREATE PROCEDURE
ON ALL SCHEMAS IN DATABASE RETAIL_UAT TO ROLE RETAIL_UAT_DEPLOYER;
GRANT CREATE TABLE, CREATE VIEW, CREATE FILE FORMAT, CREATE STAGE, CREATE PROCEDURE
ON ALL SCHEMAS IN DATABASE RETAIL_PROD TO ROLE RETAIL_PROD_DEPLOYER;
