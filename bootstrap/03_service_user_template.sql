USE ROLE USERADMIN;

CREATE USER IF NOT EXISTS SVC_GITHUB_RETAIL_CICD
TYPE=SERVICE
DEFAULT_ROLE=RETAIL_DEV_DEPLOYER
DEFAULT_WAREHOUSE=RETAIL_DEV_WH
COMMENT='GitHub Actions service user for Retail Snowflake CI/CD';

ALTER USER SVC_GITHUB_RETAIL_CICD
SET RSA_PUBLIC_KEY='<PUBLIC_KEY_WITHOUT_HEADER_FOOTER>';

USE ROLE SECURITYADMIN;
GRANT ROLE RETAIL_DEV_DEPLOYER TO USER SVC_GITHUB_RETAIL_CICD;
GRANT ROLE RETAIL_UAT_DEPLOYER TO USER SVC_GITHUB_RETAIL_CICD;
GRANT ROLE RETAIL_PROD_DEPLOYER TO USER SVC_GITHUB_RETAIL_CICD;

DESC USER SVC_GITHUB_RETAIL_CICD;
